#!/usr/bin/env bash
#
# Create the isolated test environment.
#
# WHAT IT DOES
#   1. Reads the PostgreSQL connection and media root from `.env`.
#   2. Refuses to continue if the isolated database name would collide with the
#      development database.
#   3. Creates a separate database (`dextube_isolated_test` by default) on the
#      same PostgreSQL server, plus a separate media tree and export directory.
#   4. Writes `.env.isolated-test` (git-ignored) with a freshly generated
#      SESSION_SECRET.
#   5. Applies the migrations to the isolated database only.
#
# It never touches the development database, its media, or any existing file
# outside `storage/isolated-test/`.
#
# USAGE
#   npm run isolated:setup            # create / refresh
#   npm run isolated:setup -- --force # overwrite an existing .env.isolated-test
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

CONTAINER_NAME="dextube-postgres"
ENV_FILE=".env.isolated-test"
FORCE=0
for arg in "$@"; do
  case "$arg" in
    --force) FORCE=1 ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) printf 'Unknown option: %s\n' "$arg" >&2; exit 2 ;;
  esac
done

if [[ -t 1 ]]; then
  _r=$'\033[0m'; _g=$'\033[32m'; _y=$'\033[33m'; _b=$'\033[34m'; _e=$'\033[31m'
else
  _r=''; _g=''; _y=''; _b=''; _e=''
fi
say() { printf '%s %s\n' "${_b}[isolated]${_r}" "$*"; }
ok()  { printf '%s %s\n' "${_g}[  ok  ]${_r}" "$*"; }
die() { printf '%s %s\n' "${_e}[ fail ]${_r}" "$*" >&2; exit 1; }

[[ -f .env ]] || die ".env not found. Copy .env.example to .env and configure it first."

env_value() {
  local key="$1" line
  line="$(grep -E "^[[:space:]]*${key}=" .env 2>/dev/null | tail -n1 || true)"
  [[ -z "$line" ]] && return 1
  line="${line#*=}"; line="${line%$'\r'}"; line="${line%\"}"; line="${line#\"}"; line="${line%\'}"; line="${line#\'}"
  printf '%s' "$line"
}

DEV_DATABASE_URL="$(env_value DATABASE_URL || true)"
[[ -n "$DEV_DATABASE_URL" ]] || die "DATABASE_URL is missing from .env."
POSTGRES_USER="$(env_value POSTGRES_USER || echo dextube)"
POSTGRES_PASSWORD="$(env_value POSTGRES_PASSWORD || true)"
POSTGRES_DB="$(env_value POSTGRES_DB || echo dextube)"

ISOLATED_DB="${DEXTUBE_ISOLATED_DB:-dextube_isolated_test}"
ISOLATED_MEDIA="${DEXTUBE_ISOLATED_MEDIA:-./storage/isolated-test/media}"
ISOLATED_EXPORTS="${DEXTUBE_ISOLATED_EXPORTS:-./storage/isolated-test/creator-exports}"
ISOLATED_PORT="${DEXTUBE_ISOLATED_PORT:-3001}"

# ------------------------------------------------------------- safety checks
dev_db_name="$(printf '%s' "$DEV_DATABASE_URL" | sed -E 's#^[^:]+://[^/]+/([^?]+).*#\1#')"
if [[ "$ISOLATED_DB" == "$dev_db_name" || "$ISOLATED_DB" == "$POSTGRES_DB" ]]; then
  die "Refusing to continue: the isolated database name (${ISOLATED_DB}) matches the development database (${dev_db_name})."
fi
case "$ISOLATED_DB" in
  *isolated*|*test*) : ;;
  *) die "Refusing to continue: '${ISOLATED_DB}' does not look like an isolated/test database name." ;;
esac

if [[ -f "$ENV_FILE" && "$FORCE" != "1" ]]; then
  say "${ENV_FILE} already exists — keeping it (use --force to overwrite)."
else
  say "Writing ${ENV_FILE}"
fi

# ------------------------------------------------------------- 1. database
if ! docker inspect -f '{{.State.Running}}' "$CONTAINER_NAME" >/dev/null 2>&1; then
  say "Starting PostgreSQL via docker compose"
  docker compose up -d postgres >/dev/null
fi

say "Ensuring database '${ISOLATED_DB}' exists"
exists="$(docker exec "$CONTAINER_NAME" psql -U "$POSTGRES_USER" -d postgres -tAc \
  "SELECT 1 FROM pg_database WHERE datname = '${ISOLATED_DB}'" 2>/dev/null || true)"
if [[ "$exists" == "1" ]]; then
  ok "database already exists"
else
  docker exec "$CONTAINER_NAME" psql -U "$POSTGRES_USER" -d postgres -c \
    "CREATE DATABASE \"${ISOLATED_DB}\"" >/dev/null
  ok "database created"
fi

ISOLATED_DATABASE_URL="$(printf '%s' "$DEV_DATABASE_URL" | sed -E "s#/${dev_db_name}([?].*)?\$#/${ISOLATED_DB}\\1#")"
case "$ISOLATED_DATABASE_URL" in
  */"$ISOLATED_DB"|*/"$ISOLATED_DB"?*) ;;
  *) die "Could not derive the isolated DATABASE_URL from .env (got a URL that does not end in /${ISOLATED_DB})." ;;
esac

# --------------------------------------------------------------- 2. media
say "Creating the media tree"
mkdir -p "$ISOLATED_MEDIA" "$ISOLATED_EXPORTS"
mkdir -p "$(dirname "$ISOLATED_MEDIA")/reports"
ok "$ISOLATED_MEDIA"
ok "$ISOLATED_EXPORTS"

# ------------------------------------------------------------- 3. env file
if [[ ! -f "$ENV_FILE" || "$FORCE" == "1" ]]; then
  SECRET="$(openssl rand -base64 48 2>/dev/null || head -c 48 /dev/urandom | base64)"
  # Every value is single-quoted: that is what makes `scripts/isolated.sh` safe to
  # source. None of these values contains a single quote.
  cat > "$ENV_FILE" <<EOF
# GENERATED by scripts/isolated-setup.sh — git-ignored. Disposable test config.
NODE_ENV='development'
DEXTUBE_ENV='isolated-test'
APP_URL='http://localhost:${ISOLATED_PORT}'
BIND_HOST='127.0.0.1'
PORT='${ISOLATED_PORT}'

DATABASE_URL='${ISOLATED_DATABASE_URL}'
POSTGRES_USER='${POSTGRES_USER}'
POSTGRES_PASSWORD='${POSTGRES_PASSWORD}'
POSTGRES_DB='${ISOLATED_DB}'

SESSION_SECRET='${SECRET}'
SESSION_TTL_DAYS='30'
SESSION_COOKIE_SECURE='auto'

STORAGE_DRIVER='local'
MEDIA_ROOT='${ISOLATED_MEDIA}'
MEDIA_PUBLIC_BASE='/media'
MAX_UPLOAD_BYTES='2147483648'
MAX_VIDEO_DURATION_SECONDS='7200'
PROCESSING_CONCURRENCY='1'
TRANSCODE_LADDER='480,360'
ENABLE_HLS='false'

ISOLATED_DATABASE_NAME='${ISOLATED_DB}'
ISOLATED_MEDIA_ROOT='${ISOLATED_MEDIA}'
CREATOR_EXPORT_ROOT='${ISOLATED_EXPORTS}'
NEXT_DIST_DIR='.next-isolated'

ADMIN_BOOTSTRAP_ENABLED='true'
ADMIN_BOOTSTRAP_USERNAME='admin'
ADMIN_BOOTSTRAP_EMAIL='admin@admin.com'
ADMIN_BOOTSTRAP_PASSWORD='admin'

YOUTUBE_API_KEY=''
IMPORT_MAX_ITEMS='500'
IMPORT_MAX_CONCURRENCY='4'

RATE_LIMIT_DISABLED='false'
JOB_RUNNER='inline'
WORKER_POLL_MS='2000'
EOF
  chmod 600 "$ENV_FILE"
  ok "wrote ${ENV_FILE} (mode 600)"
fi

# ------------------------------------------------------------ 4. migrations
say "Applying migrations to ${ISOLATED_DB}"
bash scripts/isolated.sh npx prisma migrate deploy >/dev/null
ok "migrations applied"

cat <<EOF

${_g}Isolated environment ready.${_r}

  database : ${ISOLATED_DB} (on the same PostgreSQL server as development)
  media    : ${ISOLATED_MEDIA}
  app      : http://localhost:${ISOLATED_PORT}   (separate build dir: .next-isolated)

Next steps:

  npm run isolated:seed               # optional: synthesised fixtures + demo data
  npm run isolated:dev                # or: npm run isolated:build && npm run isolated:start
  npm run isolated:admin              # one-time administrator (admin / admin@admin.com)
  npm run isolated:metadata-test      # the isolated ten-entry metadata test
  npm run isolated:reset -- --dry-run # see exactly what a reset would remove

Nothing here can reach the development database or its media: the reset command
verifies the database name and media root before it deletes anything.
EOF
