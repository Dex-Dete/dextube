/**
 * Sanitisation for everything that arrives from a third party.
 *
 * Imported titles, descriptions and attribution lines are attacker-controlled in
 * the general case, so they are cleaned once, here, before they reach the
 * database or a page. The rules are deliberately blunt:
 *
 *   * control characters (including `\u0000`, bidi overrides and RTL embedding
 *     marks) are stripped, because they are used to spoof text and to smuggle
 *     filenames;
 *   * all whitespace is collapsed, so a title cannot paint a fake table row with
 *     newlines or tabs;
 *   * length is capped, so one entry cannot bloat a page or a report;
 *   * URLs are only kept when they are `https:` on a host the connector trusts.
 *
 * React escapes text at render time, and storage keys are generated by DEXTube
 * rather than derived from imported text, so nothing here needs to strip HTML
 * tags for safety — but we also never render imported text as markup.
 */
import "server-only";
import { hostAllowed } from "./safe-fetch";

/** Bidi/format characters that can reorder or hide text in a UI. */
const INVISIBLE = /[\u200B-\u200F\u202A-\u202E\u2066-\u2069\uFEFF]/g;
const CONTROL = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g;

export interface SanitizeOptions {
  maxLength: number;
  /** Keep newlines (descriptions) instead of flattening everything. */
  multiline?: boolean;
}

/** Cleans a single untrusted string, or returns null when nothing is left. */
export function sanitizeText(value: unknown, options: SanitizeOptions): string | null {
  if (typeof value !== "string") return null;
  let text = value.replace(CONTROL, "").replace(INVISIBLE, "");
  text = options.multiline
    ? text.replace(/\r\n?/g, "\n").replace(/[ \t]+/g, " ").replace(/\n{3,}/g, "\n\n").trim()
    : text.replace(/\s+/g, " ").trim();
  if (!text) return null;
  return text.length > options.maxLength ? `${text.slice(0, options.maxLength - 1).trimEnd()}…` : text;
}

/** Sanitises a required field, falling back to a neutral placeholder. */
export function sanitizeRequired(value: unknown, options: SanitizeOptions, fallback = "Untitled"): string {
  return sanitizeText(value, options) ?? fallback;
}

/**
 * Keeps an `https:` URL only when its host is on the connector's allowlist.
 * Everything else becomes null — a bad thumbnail URL is dropped, never followed.
 */
export function sanitizeUrl(value: unknown, allowHosts: readonly string[]): string | null {
  if (typeof value !== "string" || value.length > 2000) return null;
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    return null;
  }
  if (url.protocol !== "https:") return null;
  if (url.username || url.password) return null;
  if (!hostAllowed(url.hostname, allowHosts)) return null;
  return url.toString();
}

/**
 * Bounds a bag of provider metadata: strings are sanitised, arrays and objects
 * are truncated, depth is capped so a crafted payload cannot blow up the store.
 */
export function sanitizeExtra(
  value: unknown,
  allowHosts: readonly string[],
  depth = 0,
): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  if (value === null || typeof value !== "object" || depth > 3) return out;
  let count = 0;
  for (const [rawKey, rawValue] of Object.entries(value as Record<string, unknown>)) {
    if (count >= 24) break;
    const key = sanitizeText(rawKey, { maxLength: 64 });
    if (!key) continue;
    count += 1;
    if (typeof rawValue === "string") {
      out[key] = sanitizeUrl(rawValue, allowHosts) ?? sanitizeText(rawValue, { maxLength: 512 });
    } else if (typeof rawValue === "number" || typeof rawValue === "boolean") {
      out[key] = rawValue;
    } else if (Array.isArray(rawValue)) {
      out[key] = rawValue
        .slice(0, 12)
        .map((item) =>
          typeof item === "string" ? sanitizeText(item, { maxLength: 256 }) : sanitizeExtra(item, allowHosts, depth + 1),
        );
    } else if (rawValue && typeof rawValue === "object") {
      out[key] = sanitizeExtra(rawValue, allowHosts, depth + 1);
    }
  }
  return out;
}
